import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { boot, call, setupAdmin } from './support/harness.ts';
import { createUser, createSession } from '../src/core/auth.ts';
import { nowSeconds, setQuietOverride } from '../src/core/domain.ts';
import { preferences, quietFor } from '../src/core/preferences.ts';

test('夜间开关按用户保存，覆盖任务和宿主请求，其他用户仍遵守夜间暂停', async (t) => {
  const { runtime } = await boot();
  const actualNow = Date.now, originalFetch = globalThis.fetch;
  t.after(async () => { Date.now = actualNow; globalThis.fetch = originalFetch; setQuietOverride(nowSeconds() + 3600); await runtime.close(); });
  const session = await setupAdmin(runtime);
  const owner = (await call(runtime, { url: '/api/me', session })).body.user.id;
  const user = await createUser(runtime.db, 'other', 'synthetic-other-passphrase', 'user', nowSeconds());
  const other = createSession(runtime.db, user.id, nowSeconds());
  runtime.manager.install(fileURLToPath(new URL('../modules/simulator', import.meta.url)));
  const begin = await call(runtime, { method: 'POST', url: '/api/platforms/sim/login', session });
  await call(runtime, { method: 'POST', url: `/api/platforms/sim/login/${begin.body.challenge.session}/poll`, session });
  const course = (await runtime.manager.courses(owner, 'sim'))[0]!;
  Date.now = () => Date.parse('2026-11-07T23:30:00+08:00'); setQuietOverride(null);
  assert.equal(preferences(runtime.db, owner).quiet_hours, true);
  assert.equal((await call(runtime, { url: '/api/bootstrap', session })).body.quiet_hours.active, true);
  assert.throws(() => runtime.jobs.create(owner, { platform: 'sim', course, operation: 'study', unit_ids: ['1001-u1'] }), /夜间暂停/);
  const row = runtime.manager.list()[0]!; const manifest = row.manifestJson;
  manifest.permissions.network = ['example.test']; manifest.permissions.browser = true;
  runtime.db.run('UPDATE modules SET manifest=?1 WHERE id=?2', JSON.stringify(manifest), 'sim');
  const handle = runtime.sessions.handleFor(owner, 'sim')!;
  const host = (method: string, params: any) => (runtime.manager as any).hostCall('sim', method, { session: handle, ...params });
  const request = { method: 'POST', url: 'https://example.test/save', stage: 'save_study' };
  await assert.rejects(host('cw.net.fetch', request), /夜间暂停/);
  await assert.rejects(host('cw.browser.evaluate', { page: 'fixture-page', expression: 'true', stage: 'save_study' }), /夜间暂停/);
  const changed = await call(runtime, { method: 'POST', url: '/api/settings/preferences', session, body: { quiet_hours: false } });
  assert.equal(changed.status, 200); assert.equal(changed.body.preferences.quiet_hours, false);
  assert.deepEqual({ enabled: quietFor(runtime.db, owner).enabled, active: quietFor(runtime.db, owner).active }, { enabled: false, active: false });
  assert.equal((await call(runtime, { url: '/api/bootstrap', session })).body.quiet_hours.active, false);
  assert.equal((await call(runtime, { url: '/api/bootstrap', session: other })).body.quiet_hours.active, true);
  globalThis.fetch = async () => new Response('{}', { status: 200 });
  assert.equal((await host('cw.net.fetch', request)).status, 200);
  runtime.browser.evaluate = async () => ({ permitted: true });
  assert.deepEqual(await host('cw.browser.evaluate', { page: 'fixture-page', expression: 'true', stage: 'save_study' }), { permitted: true });
  const task = runtime.jobs.create(owner, { platform: 'sim', course, operation: 'study', unit_ids: ['1001-u1'] });
  runtime.jobs.pause(owner, task.id); assert.equal(runtime.jobs.resume(owner, task.id).state, 'queued'); runtime.jobs.stop(owner, task.id);
  const engine = runtime.jobs as any, launch = engine.launch;
  engine.launch = () => {};
  const nightTask = runtime.jobs.create(owner, { platform: 'sim', course, operation: 'study', unit_ids: ['1001-u1'] });
  const manualTask = runtime.jobs.create(owner, { platform: 'sim', course, operation: 'study', unit_ids: ['1001-u1'] });
  runtime.jobs.pause(owner, manualTask.id);
  await call(runtime, { method: 'POST', url: '/api/settings/preferences', session, body: { quiet_hours: true } });
  engine.schedule();
  assert.equal(runtime.jobs.get(owner, nightTask.id).state, 'paused');
  assert.match(runtime.jobs.get(owner, nightTask.id).detail, /夜间暂停/);
  await call(runtime, { method: 'POST', url: '/api/settings/preferences', session, body: { quiet_hours: false } });
  engine.schedule();
  assert.equal(runtime.jobs.get(owner, nightTask.id).state, 'queued');
  assert.equal(runtime.jobs.get(owner, manualTask.id).state, 'paused');
  runtime.jobs.stop(owner, nightTask.id); runtime.jobs.stop(owner, manualTask.id); engine.launch = launch;
  assert.equal((await call(runtime, { method: 'POST', url: '/api/settings/preferences', session, body: { quiet_hours: 'false' } })).status, 400);
});
